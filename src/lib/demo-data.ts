export function getDistrictById(id: string): District | undefined {
  return demoDistricts.find((d) => d.id === id || d.name.toLowerCase() === id.toLowerCase());
}

export function getTalukasByDistrict(districtId: string): Taluka[] {
  return demoTalukas.filter((t) => t.districtId === districtId);
}

export function getVillagesByTaluka(talukaId: string): Village[] {
  return demoVillages.filter((v) => v.talukaId === talukaId);
}

export function getVillageById(id: string): Village | undefined {
  return demoVillages.find((v) => v.id === id);
}

export function getSchemeById(id: string): Scheme | undefined {
  return demoSchemes.find((s) => s.id === id);
}

