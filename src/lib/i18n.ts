const PHRASE_PATTERNS: Array<[RegExp, string]> = [
  [/^All schemes \((\d+)\)$/, "सभी योजनाएँ ($1)"],
  [/^Browse topic entries \((\d+)\)$/, "विषय प्रविष्टियाँ देखें ($1)"],
  [/^Gujarat \((\d+) districts\)$/, "गुजरात ($1 जिले)"],
  [/^All Gujarat \((\d+) districts\)$/, "पूरा गुजरात ($1 जिले)"],
  [/^Browse topic entries \((\d+)\)$/, "विषय प्रविष्टियाँ देखें ($1)"],
  [/^\[(.+)\] (.+) district$/, "[$1] $2 जिला"],
  [/^(.+) District$/, "$1 जिला"],
  [/^(.+) Taluka$/, "$1 तालुका"],
  [/^(.+) Village$/, "$1 गाँव"],
];

export function localizeText(language: AppLanguage, text: string): string {
  if (language !== "hi") return text;
  const exact = HINDI[text];
  if (exact) return exact;
  const districtLabel = text.match(/^\[(.+)\] (.+) District$/i);
  if (districtLabel) return `[${districtLabel[1]}] ${localizeText("hi", districtLabel[2])} जिला`;
  const unitLabel = text.match(/^(.+) (Taluka|Village)$/i);
  if (unitLabel) return `${localizeText("hi", unitLabel[1])} ${unitLabel[2].toLowerCase() === "taluka" ? "तालुका" : "गाँव"}`;
  for (const [pattern, replacement] of PHRASE_PATTERNS) {
    if (pattern.test(text)) return text.replace(pattern, replacement);
  }
  return text;
}

export function getLocale(language: AppLanguage): string {
  return language === "gu" ? "gu-IN" : language === "hi" ? "hi-IN" : "en-IN";
}
